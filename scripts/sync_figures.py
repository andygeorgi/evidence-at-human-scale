#!/usr/bin/env python3
"""Keep the figures in the documents in sync with their sources.

    python scripts/sync_figures.py            # rewrite every figure block and the gallery from figures/figures.json
    python scripts/sync_figures.py --check    # fail if any block or the gallery differs from what would be written

A document places a figure with a pair of markers:

    <!-- figure:F03:start -->
    <!-- figure:F03:end -->

Everything between the markers is generated: the caption, the figure (Mermaid source that GitHub renders itself, a
picture with light and dark variants, or a table) and a collapsed text description. Edit figures/figures.json and the
files in figures/src, never the generated block.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_links import slug  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
FIGURES = REPO / "figures"
META = FIGURES / "figures.json"
MARKER = re.compile(r"(<!-- figure:(F\d\d):start -->)(.*?)(<!-- figure:\2:end -->)", re.S)
GALLERY = FIGURES / "README.md"
GALLERY_MARKER = re.compile(r"(<!-- gallery:start -->)(.*?)(<!-- gallery:end -->)", re.S)
GENERATED = "<!-- Generated by scripts/sync_figures.py from figures/figures.json and the figure source. Edit those, not this block. -->"


def load():
    data = json.loads(META.read_text(encoding="utf-8"))
    return data["figures"], data.get("banner")


def relpath(from_file: Path, target: Path) -> str:
    return Path(os.path.relpath(target, from_file.parent)).as_posix()


def anchor(fig) -> str:
    return slug("%s %s" % (fig["id"], fig["title"]))


def picture(doc: Path, fig, width=860) -> str:
    light, dark = (REPO / fig["images"]["light"]), (REPO / fig["images"]["dark"])
    alt = fig["alt"].replace('"', "&quot;")
    return ('<p align="center">\n<picture>\n<source media="(prefers-color-scheme: dark)" srcset="%s">\n<img src="%s" alt="%s" width="%d">\n</picture>\n</p>'
            % (relpath(doc, dark), relpath(doc, light), alt, width))


def table_md(fig) -> str:
    t = fig["table"]
    lines = ["| " + " | ".join(t["columns"]) + " |", "|" + "---|" * len(t["columns"])]
    lines += ["| " + " | ".join(row) + " |" for row in t["rows"]]
    out = "\n".join(lines)
    if t.get("footnote"):
        out += "\n\n" + t["footnote"]
    return out


def body(doc: Path, fig) -> str:
    kind = fig["kind"]
    if kind == "mermaid":
        source = (REPO / fig["source"]).read_text(encoding="utf-8").rstrip("\n")
        return "```mermaid\n%s\n```" % source
    if kind == "svg":
        return picture(doc, fig)
    return table_md(fig)


def block(doc: Path, fig) -> str:
    gallery = relpath(doc, GALLERY) + "#" + anchor(fig)
    return "\n".join([
        GENERATED, "",
        "**Figure %s.** %s" % (fig["id"], fig["caption"]), "",
        body(doc, fig), "",
        "<details>", "<summary>Text description of Figure %s</summary>" % fig["id"], "",
        fig["description"], "",
        "[All figures and their descriptions](%s)" % gallery, "",
        "</details>", "",
    ])


def title_of(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.name


def gallery_md(figures, banner) -> str:
    out = []
    if banner:
        out += ["### Repository banner", "", picture(GALLERY, dict(banner), 900), "", "**Alt text.** " + banner["alt"], "",
                "Source: [`figures/src/svg_figures.py`](src/svg_figures.py). Files: [light](banner-light.svg) · [dark](banner-dark.svg).", ""]
    for fig in figures:
        out += ["### %s %s" % (fig["id"], fig["title"]), ""]
        if fig["kind"] == "table":
            out += [table_md(fig), ""]
        else:
            out += [picture(GALLERY, fig), ""]
        out += ["**Caption.** " + fig["caption"], "", "**Alt text.** " + fig["alt"], "", "**Description.** " + fig["description"], ""]
        used = ["[%s](%s)" % (title_of(REPO / p), relpath(GALLERY, REPO / p)) for p in fig["used_in"]]
        out += ["**Used in:** " + "; ".join(used) + ".", ""]
        if fig["kind"] == "table":
            out += ["**Source:** the table in [`figures/figures.json`](figures.json).", ""]
        else:
            files = "[light](%s) · [dark](%s)" % (Path(fig["images"]["light"]).name, Path(fig["images"]["dark"]).name)
            out += ["**Source:** [`%s`](%s). Files: %s." % (fig["source"], relpath(GALLERY, REPO / fig["source"]), files), ""]
    return "\n".join(out)


def sync(check: bool):
    figures, banner = load()
    by_id = {f["id"]: f for f in figures}
    problems, writes = [], {}
    for fig in figures:
        for rel in fig["used_in"]:
            doc = REPO / rel
            if not doc.exists():
                problems.append("%s: %s (named in figures.json) does not exist" % (fig["id"], rel))
                continue
            text = writes.get(doc) or doc.read_text(encoding="utf-8")
            found = [m for m in MARKER.finditer(text) if m.group(2) == fig["id"]]
            if len(found) != 1:
                problems.append("%s: %s needs exactly one marker pair for %s (found %d)" % (fig["id"], rel, fig["id"], len(found)))
                continue
            m = found[0]
            new_inner = "\n" + block(doc, fig)
            if m.group(3) != new_inner:
                problems.append("%s: the block in %s is out of date" % (fig["id"], rel))
            writes[doc] = text[:m.start(3)] + new_inner + text[m.end(3):]
    # markers for figures that figures.json does not know, or in documents it does not list
    for doc in sorted(REPO.rglob("*.md")):
        if any(part in (".git", "node_modules") for part in doc.parts):
            continue
        for m in MARKER.finditer(doc.read_text(encoding="utf-8")):
            fig = by_id.get(m.group(2))
            if fig is None:
                problems.append("%s has a marker for unknown figure %s" % (doc.relative_to(REPO).as_posix(), m.group(2)))
            elif doc.relative_to(REPO).as_posix() not in fig["used_in"]:
                problems.append("%s places %s but figures.json does not list it in used_in" % (doc.relative_to(REPO).as_posix(), m.group(2)))
    gtext = GALLERY.read_text(encoding="utf-8") if GALLERY.exists() else ""
    gm = GALLERY_MARKER.search(gtext)
    if gm is None:
        problems.append("figures/README.md needs <!-- gallery:start --> and <!-- gallery:end --> markers")
    else:
        inner = "\n" + GENERATED + "\n\n" + gallery_md(figures, banner) + "\n"
        if gm.group(2) != inner:
            problems.append("the gallery in figures/README.md is out of date")
        writes[GALLERY] = gtext[:gm.start(2)] + inner + gtext[gm.end(2):]
    if not check:
        for doc, text in writes.items():
            if doc.read_text(encoding="utf-8") != text:
                doc.write_bytes(text.encode("utf-8"))
                print("updated " + doc.relative_to(REPO).as_posix())
        return [p for p in problems if "does not exist" in p or "marker" in p]
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    problems = sync(args.check)
    for p in problems:
        print("FIGURE  " + p)
    if problems:
        print("\nRun python scripts/sync_figures.py to regenerate." if args.check else "")
        return 1
    print("Figure blocks and gallery are in sync." if args.check else "Figure blocks and gallery written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
