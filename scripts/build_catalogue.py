#!/usr/bin/env python3
"""Write the CSV copies of the evaluation catalogue and the test sections of the oracles page from the JSON tables.

    python scripts/build_catalogue.py            # rewrite the CSV files and the generated block of evaluation/oracles.md
    python scripts/build_catalogue.py --check    # fail if any of them differs, or if the tables contradict one another

evaluation/catalogue/*.json is the source. The CSV files, and the block of evaluation/oracles.md between
<!-- catalogue:start --> and <!-- catalogue:end -->, are derived from it. Edit the JSON, never the copies.

The check also holds the tables to what they claim. Every status is one of the five defined states. A row has a ``run`` record
(command, input and output) exactly when its status says it was run. A test cannot be RUN / PASS unless every one of its fixtures
is, and one failed fixture cannot be hidden by a test that says otherwise. The contracts listed for a fixture are the ones named by
the schema examples and contract IDs in its own text, and a test lists the union of its fixtures'. Every reference resolves.
Exit code 0 means everything is current and consistent.
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_links import slug  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
CATALOGUE = REPO / "evaluation" / "catalogue"
ORACLES = REPO / "evaluation" / "oracles.md"
SCHEMA = REPO / "schemas" / "contracts-v1.schema.json"

TABLES = ("evaluation-tests", "fixtures", "matched-baselines", "domain-parameters")
KEY = {"evaluation-tests": "id", "fixtures": "fixture_id", "matched-baselines": "id", "domain-parameters": "parameter_id"}
FIELDS = {
    "evaluation-tests": ("id", "short_name", "summary", "contracts", "status"),
    "fixtures": ("fixture_id", "evaluation_id", "scenario", "input_definition", "perturbation_or_adversarial_opportunity",
                 "expected_oracle", "metric", "gate_mode", "contracts", "status"),
    "matched-baselines": ("id", "measure", "comparison_baseline", "metric", "status"),
    "domain-parameters": ("parameter_id", "parameter", "required_type", "units_and_scope", "rationale", "used_by", "status"),
}
RUN_FIELDS = ("command", "input", "output")
# RUN / PASS and RUN / FAIL need a recorded run. The other three say why there is none.
STATES = ("RUN / PASS", "RUN / FAIL", "NOT RUN", "NOT ASSESSED", "UNSET")
GATES = {"ratio": "ratio 1", "zero": "zero 0"}

START = "<!-- catalogue:start -->"
END = "<!-- catalogue:end -->"
BLOCK = re.compile(r"(" + re.escape(START) + r")(.*?)(" + re.escape(END) + r")", re.S)
GENERATED = "<!-- Generated by scripts/build_catalogue.py from evaluation/catalogue/*.json. Edit those, not this block. -->"

EXAMPLE_REFERENCE = re.compile(r"(x-documentation-examples|examples)\[(\d+)\]")
CONTRACT_MENTION = re.compile(r"\bC0[1-7]\b")


def load_tables() -> Dict[str, List[dict]]:
    return {name: json.loads((CATALOGUE / (name + ".json")).read_text(encoding="utf-8")) for name in TABLES}


def load_schema() -> dict:
    return json.loads(SCHEMA.read_text(encoding="utf-8"))


def contracts_of(fixture: dict, schema: dict) -> List[str]:
    """The contracts a fixture touches: those of the schema examples it starts from or perturbs, and any it names itself."""
    valid = [entry["contract_id"] for entry in schema["x-valid-example-index"]]
    invalid = [entry["contract_id"] for entry in schema["x-documentation-examples"]]
    text = " ".join((fixture["input_definition"], fixture["perturbation_or_adversarial_opportunity"], fixture["expected_oracle"]))
    found = set(CONTRACT_MENTION.findall(text))
    for kind, number in EXAMPLE_REFERENCE.findall(text):
        source = invalid if kind.startswith("x-") else valid
        if int(number) >= len(source):
            raise IndexError("%s[%s] does not exist in the schema" % (kind, number))
        found.add(source[int(number)])
    return sorted(found)


def cell(value) -> str:
    """How a JSON value is written into a CSV cell: a list is joined with ' | ', null is empty."""
    if value is None:
        return ""
    if isinstance(value, list):
        return " | ".join(str(item) for item in value)
    return str(value)


def columns(name: str, rows: List[dict]) -> List[str]:
    extra = ["run_" + field for field in RUN_FIELDS] if any("run" in row for row in rows) else []
    return list(FIELDS[name]) + extra


def csv_text(name: str, rows: List[dict]) -> str:
    out = io.StringIO(newline="")
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(columns(name, rows))
    with_run = any("run" in row for row in rows)
    for row in rows:
        values = [cell(row.get(field)) for field in FIELDS[name]]
        if with_run:
            values += [cell((row.get("run") or {}).get(field)) for field in RUN_FIELDS]
        writer.writerow(values)
    return out.getvalue()


def md(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def heading_of(test: dict) -> str:
    return "%s %s" % (test["id"], test["short_name"])


def render_block(tests: List[dict], fixtures: List[dict]) -> str:
    """The text between the markers: a table of the tests, then one section for each with its fixtures."""
    by_test = {test["id"]: [f for f in fixtures if f["evaluation_id"] == test["id"]] for test in tests}
    lines = [GENERATED, "", "## The twelve tests at a glance", "",
             "| Test | Name | Fixtures | Contracts | Status |", "|---|---|---|---|---|"]
    for test in tests:
        lines.append("| [%s](#%s) | %s | %d | %s | %s |" % (
            test["id"], slug(heading_of(test)), md(test["short_name"]), len(by_test[test["id"]]), ", ".join(test["contracts"]), test["status"]))
    for test in tests:
        lines += ["", "## " + heading_of(test), "", md(test["summary"]), "",
                  "Contracts: %s. Status: %s." % (", ".join(test["contracts"]), test["status"]), "",
                  "| Fixture | Scenario | Expected oracle | Metric | Gate |", "|---|---|---|---|---|"]
        for fixture in by_test[test["id"]]:
            lines.append("| %s | %s | %s | %s | %s |" % (
                fixture["fixture_id"], md(fixture["scenario"]), md(fixture["expected_oracle"]), md(fixture["metric"]), GATES[fixture["gate_mode"]]))
    return "\n" + "\n".join(lines) + "\n"


def consistency(tables: Dict[str, List[dict]], schema: Optional[dict] = None) -> List[str]:
    """Everything the tables claim, checked without reading the generated copies."""
    out: List[str] = []
    for name in TABLES:
        allowed = set(FIELDS[name]) | {"run"}
        seen = set()
        for row in tables[name]:
            ident = str(row.get(KEY[name], "?"))
            where = "%s %s" % (name, ident)
            if ident in seen:
                out.append("%s: duplicate identifier" % where)
            seen.add(ident)
            for field in sorted(set(FIELDS[name]) - set(row)):
                out.append("%s: missing field %s" % (where, field))
            for field in sorted(set(row) - allowed):
                out.append("%s: unexpected field %s" % (where, field))
            status = row.get("status")
            if status not in STATES:
                out.append("%s: status %r is not one of %s" % (where, status, ", ".join(STATES)))
            if name == "domain-parameters" and status != "UNSET":
                out.append("%s: a parameter in this catalogue is UNSET; a domain that sets one keeps its own copy" % where)
            ran = isinstance(status, str) and status.startswith("RUN")
            if ran != ("run" in row):
                out.append("%s: status %s %s a run record" % (where, status, "needs" if ran else "must not have"))
            elif ran:
                record = row["run"]
                for field in RUN_FIELDS:
                    if not isinstance(record, dict) or not str(record.get(field, "")).strip():
                        out.append("%s: the run record has no %s" % (where, field))
    tests, fixtures, params = tables["evaluation-tests"], tables["fixtures"], tables["domain-parameters"]
    test_ids = [test["id"] for test in tests]
    by_test = {test_id: [f for f in fixtures if f["evaluation_id"] == test_id] for test_id in test_ids}
    for fixture in fixtures:
        if fixture["evaluation_id"] not in test_ids:
            out.append("fixture %s belongs to unknown test %s" % (fixture["fixture_id"], fixture["evaluation_id"]))
        elif fixture["fixture_id"][2:4] != fixture["evaluation_id"][2:4]:
            out.append("fixture %s is filed under %s" % (fixture["fixture_id"], fixture["evaluation_id"]))
        if fixture["gate_mode"] not in GATES:
            out.append("fixture %s: gate_mode %r is not one of %s" % (fixture["fixture_id"], fixture["gate_mode"], ", ".join(GATES)))
    for test in tests:
        states = [f["status"] for f in by_test[test["id"]]]
        if not states:
            out.append("test %s has no fixtures" % test["id"])
        if test["status"] == "RUN / PASS" and any(state != "RUN / PASS" for state in states):
            out.append("test %s is RUN / PASS but not every fixture is" % test["id"])
        if "RUN / FAIL" in states and test["status"] != "RUN / FAIL":
            out.append("test %s hides a failed fixture behind %s" % (test["id"], test["status"]))
        if test["status"] == "RUN / FAIL" and "RUN / FAIL" not in states:
            out.append("test %s is RUN / FAIL but no fixture failed" % test["id"])
    for param in params:
        for reference in param["used_by"]:
            if reference != "BASE" and reference not in test_ids:
                out.append("parameter %s is used by unknown test %s" % (param["parameter_id"], reference))
    try:
        schema = schema or load_schema()
        for fixture in fixtures:
            derived = contracts_of(fixture, schema)
            if fixture["contracts"] != derived:
                out.append("fixture %s lists contracts %s but its own references name %s" % (fixture["fixture_id"], fixture["contracts"], derived))
        for test in tests:
            union = sorted({c for f in by_test[test["id"]] for c in f["contracts"]})
            if test["contracts"] != union:
                out.append("test %s lists contracts %s but its fixtures cover %s" % (test["id"], test["contracts"], union))
    except (IndexError, KeyError) as error:
        out.append("contract mapping could not be derived: %s" % error)
    return out


def generated_files(tables: Dict[str, List[dict]]) -> Dict[Path, str]:
    """Every derived file and what it must contain. The oracles page is returned whole, with the block replaced."""
    files = {CATALOGUE / (name + ".csv"): csv_text(name, tables[name]) for name in TABLES}
    page = ORACLES.read_text(encoding="utf-8")
    found = BLOCK.search(page)
    if found is None:
        raise ValueError("evaluation/oracles.md needs %s and %s markers" % (START, END))
    files[ORACLES] = page[:found.start(2)] + render_block(tables["evaluation-tests"], tables["fixtures"]) + page[found.end(2):]
    return files


def problems(tables: Optional[Dict[str, List[dict]]] = None, schema: Optional[dict] = None, files: bool = True) -> List[str]:
    tables = tables if tables is not None else load_tables()
    out = consistency(tables, schema)
    if files and not out:
        try:
            for path, want in generated_files(tables).items():
                have = path.read_bytes().decode("utf-8") if path.exists() else None
                if have != want:
                    out.append("%s is out of date" % path.relative_to(REPO).as_posix())
        except ValueError as error:
            out.append(str(error))
    return out


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="report what would change instead of writing it")
    args = parser.parse_args(argv)
    tables = load_tables()
    found = consistency(tables)
    if not found and not args.check:
        for path, want in generated_files(tables).items():
            if not path.exists() or path.read_bytes().decode("utf-8") != want:
                path.write_bytes(want.encode("utf-8"))
                print("updated " + path.relative_to(REPO).as_posix())
    elif not found:
        found = problems(tables, files=True)
    for line in found:
        print("CATALOGUE  " + line)
    if found:
        print("\nEdit evaluation/catalogue/*.json, then run python scripts/build_catalogue.py." if args.check else "")
        return 1
    counts = ", ".join("%d %s" % (len(tables[name]), name.replace("-", " ")) for name in TABLES)
    print("Catalogue copies are current and consistent (%s)." % counts if args.check else "Catalogue copies written (%s)." % counts)
    return 0


if __name__ == "__main__":
    for _stream in (sys.stdout, sys.stderr):  # a legacy console code page must not break the output
        getattr(_stream, "reconfigure", lambda **_: None)(encoding="utf-8", errors="replace")
    sys.exit(main())
